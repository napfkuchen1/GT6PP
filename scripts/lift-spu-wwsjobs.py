#!/usr/bin/env python
"""Lift the WWS job modules stored in the PPU ELF and generate their overlay registry.

  python -I scripts/lift-spu-wwsjobs.py [--list]

The WWS job-manager policy module (image 5) DMAs job modules from the ELF's data into
local store 0x4000 and branches into them. Without a lift they run in the SPU
interpreter (seen as one busy thread and <1 FPS on the car view).

Module header (16-byte aligned): four `ila $r2` words, 0x30, text size, data size,
bss size. The DMA'd body is text + data. Each module is lifted at base 0x4000 into
gt6/generated/spu_lifted/wwsjobs/<ea>/ and registered as a verified overlay region
(source EA, load LSA 0x4000, text size) in gt6/src/gen/spu_workloads_wwsjobs.c.
The registry holds addresses and sizes only; the code bytes come from guest memory.
"""
import shutil, struct, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SDK = ROOT / "third_party" / "ps3recomp-v020" / "tools"
ELF = ROOT / "work" / "bin" / "EMAIN.elf"
OUT = ROOT / "gt6" / "generated" / "spu_lifted" / "wwsjobs"
WORK = ROOT / "work" / "spu_jobs" / "wws_analysis"
REG = ROOT / "gt6" / "src" / "gen" / "spu_workloads_wwsjobs.c"
LOAD_LSA = 0x4000
FIRST_IMAGE_ID = 40


def segments(elf):
    phoff = struct.unpack_from(">Q", elf, 0x20)[0]
    for i in range(struct.unpack_from(">H", elf, 0x38)[0]):
        p = phoff + i * 56
        if struct.unpack_from(">I", elf, p)[0] == 1:
            off, va = struct.unpack_from(">QQ", elf, p + 8)
            yield off, va, struct.unpack_from(">Q", elf, p + 32)[0]


def modules(elf):
    for off, va, size in segments(elf):
        for o in range((off + 15) & ~15, off + size - 32, 16):
            if struct.unpack_from(">I", elf, o + 16)[0] != 0x30:
                continue
            w = elf[o:o + 16]
            if not all(w[k] in (0x42, 0x43) and w[k + 3] & 0x7F == 2 for k in (0, 4, 8, 12)):
                continue
            text, data, bss = struct.unpack_from(">III", elf, o + 20)
            if (0x30 < text and not (text | data) & 15 and LOAD_LSA + text + data + bss <= 0x40000
                    and o + text + data <= off + size):
                yield va + o - off, o, text, data, bss


def main():
    elf = ELF.read_bytes()
    mods = list(modules(elf))
    for ea, o, text, data, bss in mods:
        print("module ea 0x%08X text 0x%05X data 0x%05X bss 0x%05X" % (ea, text, data, bss))
    print("%d modules, %d bytes of code" % (len(mods), sum(m[2] for m in mods)))
    if "--list" in sys.argv:
        return
    if not mods:
        sys.exit("no WWS job modules found")
    if OUT.exists():  # never delete: park the old tree outside the CMake glob
        arch = ROOT / "work" / "ARCHIV" / ("wwsjobs." + time.strftime("%Y%m%d-%H%M%S"))
        arch.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(OUT), str(arch))
    OUT.mkdir(parents=True)
    WORK.mkdir(parents=True, exist_ok=True)
    for ea, o, text, data, bss in mods:
        name = "%08X" % ea
        body, funcs, code = WORK / (name + ".bin"), WORK / (name + ".json"), WORK / (name + ".code.bin")
        body.write_bytes(elf[o:o + text])
        for cmd in ([sys.executable, "-I", str(SDK / "find_spu_functions.py"), str(body), "--raw",
                     "--base", hex(LOAD_LSA), "--code-out", str(code), "--out", str(funcs)],
                    [sys.executable, str(SDK / "spu_lifter.py"), str(code), "--base", hex(LOAD_LSA),
                     "--functions", str(funcs), "--symbol-prefix", "wws_%s_" % name.lower(),
                     "--output", str(OUT / name), "--source-name", "spu_recomp.c",
                     "--header-name", "spu_recomp.h"]):
            r = subprocess.run(cmd, capture_output=True, text=True)
            (WORK / (name + "." + Path(cmd[-1 if "-I" not in cmd else 2]).stem + ".log")).write_text(
                r.stdout + r.stderr)
            if r.returncode:
                sys.exit("%s failed for %s:\n%s" % (cmd[1], name, r.stderr[-2000:]))
        print("lifted " + name, flush=True)

    c = ["/* WWS job modules in the PPU ELF, loaded by the policy module at LS 0x%X." % LOAD_LSA,
         " * GENERATED by scripts/lift-spu-wwsjobs.py; do not edit by hand. */",
         '#include "spu_workload.h"', '#include "spu_overlay_residency.h"', "#include <stdio.h>", "",
         "extern void spu_begin_image(int image_id);", "extern uint8_t* vm_base;", ""]
    c += ["extern void wws_%08x_spu_recomp_register(void);" % m[0] for m in mods]
    c += ["", "void gt6_spu_register_wwsjobs(void)", "{",
          "    static const struct { uint32_t ea, text; void (*reg)(void); } m[] = {"]
    c += ["        { 0x%08Xu, 0x%05Xu, wws_%08x_spu_recomp_register }," % (m[0], m[2], m[0]) for m in mods]
    c += ["    };",
          "    for (unsigned i = 0; i < sizeof m / sizeof m[0]; i++) {",
          "        const int image = %d + (int)i;" % FIRST_IMAGE_ID,
          "        const spu_overlay_code_segment code = { 0x%Xu, m[i].text, vm_base + m[i].ea };" % LOAD_LSA,
          "        spu_begin_image(image);",
          "        m[i].reg();",
          "        if (!spu_overlay_register_verified_region(m[i].ea, 0x%Xu, m[i].text, image, &code, 1))" % LOAD_LSA,
          '            fprintf(stderr, "[spu-ovl] WWS job 0x%08X not registered\\n", m[i].ea);',
          "    }", "    spu_begin_image(0);", "}", ""]
    REG.write_text("\n".join(c), newline="\n")
    print("wrote %s (images %d..%d)" % (REG, FIRST_IMAGE_ID, FIRST_IMAGE_ID + len(mods) - 1))


if __name__ == "__main__":
    main()
